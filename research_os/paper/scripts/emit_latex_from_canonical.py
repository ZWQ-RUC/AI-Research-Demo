#!/usr/bin/env python3
"""Emit LaTeX macros and tables from canonical snapshot.

Reads research_os/paper/canonical/data.json only.
Never writes under experiments/.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any


SCRIPT_DIR = Path(__file__).resolve().parent
PAPER_DIR = SCRIPT_DIR.parent
PROJECT_ROOT = PAPER_DIR.parent.parent

DEFAULT_CANONICAL = PAPER_DIR / "canonical" / "data.json"
DEFAULT_LATEX_DIR = PAPER_DIR / "latex"


def die(msg: str, code: int = 1) -> None:
    print(f"ERROR: {msg}", file=sys.stderr)
    raise SystemExit(code)


def fmt_pct(x: float | None) -> str:
    if x is None:
        return "---"
    # Keep two decimals as in project docs
    return f"{float(x):.2f}"


def tex_escape(s: str) -> str:
    return (
        s.replace("\\", "\\textbackslash{}")
        .replace("&", "\\&")
        .replace("%", "\\%")
        .replace("_", "\\_")
        .replace("#", "\\#")
    )


def write_macros(data: dict[str, Any], path: Path) -> None:
    s = data["scalars"]
    lines = [
        "% AUTO-GENERATED by research_os/paper/scripts/emit_latex_from_canonical.py",
        "% Do not edit by hand. Re-run pipeline after rebuild_canonical.",
        f"% frozen_at_utc: {data.get('frozen_at_utc')}",
        f"% git_head: {data.get('git_head')}",
        "",
        f"\\newcommand{{\\ErrPlain}}{{{fmt_pct(s['err_plain'])}}}",
        f"\\newcommand{{\\ErrResNet}}{{{fmt_pct(s['err_resnet'])}}}",
        f"\\newcommand{{\\ErrPreAct}}{{{fmt_pct(s['err_preact'])}}}",
        f"\\newcommand{{\\ErrAblationA}}{{{fmt_pct(s['err_ablation_a'])}}}",
        f"\\newcommand{{\\AblationBStatus}}{{{tex_escape(str(s['ablation_b_status']))}}}",
        f"\\newcommand{{\\ResidualAdvantagePP}}{{{fmt_pct(s['residual_advantage_pp'])}}}",
        f"\\newcommand{{\\DeltaPlainMinusResNet}}{{{fmt_pct(s['delta_plain_minus_resnet_pp'])}}}",
        f"\\newcommand{{\\DeltaResNetMinusPlain}}{{{fmt_pct(s['delta_resnet_minus_plain_pp'])}}}",
        f"\\newcommand{{\\DeltaPreActMinusResNet}}{{{fmt_pct(s['delta_preact_minus_resnet_pp'])}}}",
        f"\\newcommand{{\\DeltaAblationAMinusResNet}}{{{fmt_pct(s['delta_ablation_a_minus_resnet_pp'])}}}",
        f"\\newcommand{{\\DeltaAblationAMinusPreAct}}{{{fmt_pct(s['delta_ablation_a_minus_preact_pp'])}}}",
        # Magnitudes used in narrative (proposal-compatible aliases)
        f"\\newcommand{{\\DeltaPreActVsResNet}}{{{fmt_pct(abs(s['delta_preact_minus_resnet_pp']))}}}",
        f"\\newcommand{{\\DeltaAblationAVsPreAct}}{{{fmt_pct(abs(s['delta_ablation_a_minus_preact_pp']))}}}",
        f"\\newcommand{{\\PaperResNetRef}}{{{fmt_pct(s['paper_resnet20_table6_pct'])}}}",
        f"\\newcommand{{\\RepoPlainRef}}{{{fmt_pct(s['repo_plain_ref_pct'])}}}",
        f"\\newcommand{{\\RepoResNetRef}}{{{fmt_pct(s['repo_resnet_ref_pct'])}}}",
        f"\\newcommand{{\\ReproStatus}}{{{tex_escape(str(s['reproduction_status']))}}}",
        f"\\newcommand{{\\ReproTolerancePP}}{{{fmt_pct(s['tolerance_pp'])}}}",
        "",
    ]
    path.write_text("\n".join(lines), encoding="utf-8")


def write_main_results(data: dict[str, Any], path: Path) -> None:
    rows = []
    for m in data["models"]:
        err = m.get("best_test_error_pct")
        err_s = fmt_pct(err) if m.get("status") == "completed" else "N/A"
        status = m.get("status") or ""
        if m.get("failure_mode"):
            status = f"{status} ({m['failure_mode']})"
        rows.append(
            "  {name} & {err} & {epoch} & {params} & {status} \\\\".format(
                name=tex_escape(m["display_name"]),
                err=err_s,
                epoch=m["best_epoch"] if m.get("best_epoch") is not None else "---",
                params=f"{m['param_count']:,}" if m.get("param_count") is not None else "---",
                status=tex_escape(status),
            )
        )
    body = "\n".join(rows)
    tex = f"""% AUTO-GENERATED — do not edit by hand
% Source: research_os/paper/canonical/data.json
\\begin{{tabular}}{{lrrrl}}
\\toprule
Model & Best test err. (\\%) & Best epoch & Params & Status \\\\
\\midrule
{body}
\\bottomrule
\\end{{tabular}}
"""
    path.write_text(tex, encoding="utf-8")


def write_deltas(data: dict[str, Any], path: Path) -> None:
    d = data["deltas_pp"]
    tex = f"""% AUTO-GENERATED — do not edit by hand
\\begin{{tabular}}{{lr}}
\\toprule
Comparison & $\\Delta$ best test err. (pp) \\\\
\\midrule
ResNet-20-A $-$ Plain-20 & {fmt_pct(d['resnet_minus_plain'])} \\\\
PreAct $-$ ResNet-20-A & {fmt_pct(d['preact_minus_resnet20a'])} \\\\
Ablation-A $-$ ResNet-20-A & {fmt_pct(d['ablation_a_minus_resnet20a'])} \\\\
Ablation-A $-$ PreAct & {fmt_pct(d['ablation_a_minus_preact'])} \\\\
\\bottomrule
\\end{{tabular}}
"""
    path.write_text(tex, encoding="utf-8")


def main() -> int:
    parser = argparse.ArgumentParser(description="Emit LaTeX from canonical snapshot.")
    parser.add_argument("--canonical", type=Path, default=DEFAULT_CANONICAL)
    parser.add_argument("--latex-dir", type=Path, default=DEFAULT_LATEX_DIR)
    args = parser.parse_args()

    latex_dir = args.latex_dir.resolve()
    experiments_root = (PROJECT_ROOT / "experiments").resolve()
    if experiments_root in latex_dir.parents or latex_dir == experiments_root:
        die("refusing to write under experiments/")

    if not args.canonical.is_file():
        die(f"canonical missing: {args.canonical} (run build_canonical_data.py first)")

    data = json.loads(args.canonical.read_text(encoding="utf-8"))
    if not data.get("consistency", {}).get("ok", False):
        die("canonical consistency.ok is false; refuse to emit LaTeX")

    tables = latex_dir / "tables"
    tables.mkdir(parents=True, exist_ok=True)

    macros = latex_dir / "macros.tex"
    main_tex = tables / "main_results.tex"
    deltas_tex = tables / "deltas.tex"

    write_macros(data, macros)
    write_main_results(data, main_tex)
    write_deltas(data, deltas_tex)

    print(f"wrote {macros.relative_to(PROJECT_ROOT)}")
    print(f"wrote {main_tex.relative_to(PROJECT_ROOT)}")
    print(f"wrote {deltas_tex.relative_to(PROJECT_ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
